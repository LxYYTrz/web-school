-- ============================================================================
-- 004_line_state_stages.sql
--   契约 v1.1 扩展：产线状态从 4 态放宽为 4 态 + 10 种工序状态（共 14 个合法值）
-- 所属目录：db/init/（产线数字孪生平台 · 数据层 · 增量迁移）
-- ============================================================================
--
-- 【文件作用】
--   一次**枚举放宽**：把产线状态的允许取值从原来 4 种
--   （running 运行 / idle 空闲 / alarm 报警 / offline 离线）
--   扩到 14 种 —— 原 4 种保留不动，再加上现场的 10 种工序状态。
--
-- 【为什么必须扩：不扩会直接丢数据】
--   原设计里状态只有"在跑 / 闲着 / 出问题了 / 不在线"四种，
--   但真实产线复杂得多：等待入料、入料中、装配中、下料中、下料完成、
--   等待后站入料，外加初始化错误、停止、手动控制模式，一共 10 种。
--   ★ 如果数据库还锁死在 4 种，PLC 真实上报的状态会被数据库**直接拒收**
--     （CHECK 违规），表现是：写入报约束冲突、页面状态不更新、
--     历史曲线断档——而且报错信息指向数据库，很难第一时间想到是枚举太窄。
--   这条迁移就是修这个问题的。
--
-- 【依据】
--   这份历史迁移曾按旧口径将 3 标作 unloading。实际 PLC 状态位于 word 6，
--   采集器通过 STATE_MAP 转换为契约字符串；005_line_state_waiting_robot.sql
--   已补充正确的 waiting_robot，同时保留 unloading 兼容历史数据。
--
-- 【新枚举（PLC 原始整数 → 中文）】
--        0 = 等待入料         1 = 入料中           2 = 装配中
--        3 = 下料中           4 = 下料完成         5 = 等待后站入料
--      100 = 初始化错误状态 101 = 停止状态        102 = 手动控制模式
--
-- 【谁负责翻译、翻译在哪一步发生】
--   ★ 分工是"各管一段"，不要搞混：
--     · PLC → 契约字符串：采集器做。edge/plc_collector.py 的 STATE_MAP
--       把整数映射成 waiting_feed / feeding / …；查不到的整数兜底成 offline。
--     · 契约字符串 → 中文名与颜色：前端做。web/src/services/lineState.ts
--       管中文名（等待入料 / 入料中 / …）与语义色，web/src/styles.css 配配色，
--       App.vue / IoPanel.vue 负责展示。
--     · 数据库这一层**只管"收下合法的字符串"**——它不认识 0/1/100 这些数字，
--       也不负责翻译。翻译逻辑放在数据库会导致换 PLC 就要改表。
--
-- 【兼容策略：只增不改】
--   · 保留原 4 态值，新 10 态并排加上去，老数据都还能正常写，
--     mock 采集器（它发的还是原 4 态里的 'running'）也不受影响，兼容性零风险。
--   · 契约铁律"只增不改"在这里的体现：枚举只能加，不能删、不能改。
--
-- 【执行方式】
--   全新部署按文件名顺序执行；存量库只执行尚未应用的迁移：
--        psql -U postgres -d linetwin -f db\init\004_line_state_stages.sql
--
-- 【幂等性与执行注意事项】
--   · 本脚本**幂等**：两条 DROP CONSTRAINT 都带 IF EXISTS，
--     重复执行安全（ADD CONSTRAINT 同名会先被 DROP 掉，不会报"已存在"）。
--   · ADD CONSTRAINT 会对存量行做一次全表校验。本次是"放宽"（新集合是旧集合的
--     超集），存量行一定还能通过，不会因为老数据而失败。
--   · ALTER TABLE 会拿 ACCESS EXCLUSIVE 锁，事务期间这两张表不能读写。
--     在线上的库里执行时挑个业务低峰。
--
-- 【注意】001/002/003 不动，符合"只增不改"
--
-- 【本文件用到的 SQL 关键字】
--   ALTER TABLE       改表结构
--   DROP CONSTRAINT   删掉一条约束
--   IF EXISTS         存在才执行（不存在就跳过，不报错）—— 幂等的关键
--   ADD CONSTRAINT    加一条约束
--   CHECK             行级校验，写不进表
--   IN (...)          枚举白名单，配合 CHECK 使用
--   COMMENT ON TABLE  给表写数据库注释（psql \d+ 能看到，pg_dump 也会导出去）
-- ============================================================================
--
-- 【契约与来源】
--   契约 v1.1 扩展：line_status.state 从 4 态扩为 10 态（工序状态）。
--   依据：DB3-Modbus-映射表.xls「产线状态」枚举。
--
-- 【兼容策略】
--   - 只增不改（契约铁律），保留原 4 态值，新枚举与之并存
--   - 前端 lineState.ts 维护中文映射，未知值回退显示原值
--   - plc_collector.py 通过 STATE_MAP 转换 PLC 整数
--
-- 【触发场景】
--   1. 全新部署：按文件名顺序执行 db/init/*.sql（001 → … → 004）
--   2. 已在运行的库：
--      psql -U postgres -d linetwin -f db/init/004_line_state_stages.sql
--
-- 【注意】
--   001/002/003 不动，符合"只增不改"。

